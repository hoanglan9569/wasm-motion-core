/**
 * Build the Rust core to WebAssembly and emit the base64 module the runtime
 * imports, so a page needs no extra request and works over file://.
 *   bun run build
 * Needs: rustup target add wasm32-unknown-unknown
 */
import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const crate = join(root, 'crate');
const built = join(crate, 'target', 'wasm32-unknown-unknown', 'release', 'motion_core.wasm');
const runtime = join(root, 'runtime');

const run = spawnSync('cargo', ['build', '--release', '--target', 'wasm32-unknown-unknown'], {
  cwd: crate,
  stdio: 'inherit',
  shell: process.platform === 'win32',
});
if (run.status !== 0) {
  console.error('cargo build failed (needs: rustup target add wasm32-unknown-unknown)');
  process.exit(run.status ?? 1);
}

const bytes = readFileSync(built);
const b64 = bytes.toString('base64');
writeFileSync(join(runtime, 'motion-core.wasm'), bytes);
writeFileSync(
  join(runtime, 'motion-core-wasm.ts'),
  `// Generated by scripts/build.ts - do not edit.\n` +
    `// crate/ compiled to WebAssembly, ${bytes.length} bytes, inlined as base64.\n` +
    `export const MOTION_CORE_WASM = '${b64}';\n`,
);
console.log(`motion-core.wasm: ${bytes.length} bytes -> ${b64.length} base64 chars`);
